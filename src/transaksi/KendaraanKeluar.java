    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {

    if (idTransaksi == null || idTransaksi.equals("")) {

        JOptionPane.showMessageDialog(
                null,
                "Pilih transaksi terlebih dahulu");

        return;
    }

    SimpleDateFormat sdf =
            new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");

    Date waktuMasuk =
            sdf.parse(jTextField1.getText());

    Date waktuKeluar =
            new Date();

    jTextField2.setText(sdf.format(waktuKeluar));

    long selisihMillis =
            waktuKeluar.getTime() - waktuMasuk.getTime();

    long durasiJam =
            TimeUnit.MILLISECONDS.toHours(selisihMillis);

    if (selisihMillis % (1000 * 60 * 60) != 0) {
        durasiJam++;
    }

    if (durasiJam <= 0) {
        durasiJam = 1;
    }

    int total;

    if (durasiJam <= 1) {
        total = tarifMinimum;
    } else {
        total = tarifMinimum
                + (int) ((durasiJam - 1) * tarifPerjam);
    }

    jTextField3.setText(String.valueOf(total));

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            null,
            "Gagal menghitung tarif : "
            + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

