    private void tampilData() {

    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID Tarif");
    model.addColumn("Tarif Minimal");
    model.addColumn("Tarif Per Jam");
    model.addColumn("Jenis Kendaraan");

    try {

        Connection conn = koneksi.getConnection();
        String sql = "SELECT * FROM tarif";
        Statement st = conn.createStatement();
        ResultSet rs = st.executeQuery(sql);

        while (rs.next()) {

            model.addRow(new Object[]{

                rs.getString("id_tarif"),
                rs.getString("tarif_minimum"),
                rs.getString("tarif_perjam"),
                rs.getString("jenis_kendaraan")

            });

        }

        jTable1.setModel(model);

    } catch (Exception e) {

        JOptionPane.showMessageDialog(null,
                "Gagal Menampilkan Data : " + e.getMessage());

    }
}
