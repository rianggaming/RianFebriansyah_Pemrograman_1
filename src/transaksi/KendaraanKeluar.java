    public void loadTransaksiParkir() {

    try {

        Connection conn = koneksi.getConnection();

        String sql =
                "SELECT transaksi.id_transaksi, kendaraan.no_polisi, kendaraan.jenis_kendaraan "
                + "FROM transaksi "
                + "JOIN kendaraan ON transaksi.id_kendaraan = kendaraan.id_kendaraan "
                + "WHERE transaksi.status='Parkir'";

        PreparedStatement pst = conn.prepareStatement(sql);

        ResultSet rs = pst.executeQuery();

        jComboBox1.removeAllItems();

        while (rs.next()) {

            jComboBox1.addItem(
                    rs.getString("id_transaksi")
                    + " - "
                    + rs.getString("no_polisi")
                    + " - "
                    + rs.getString("jenis_kendaraan"));
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                null,
                "Gagal memuat transaksi parkir : "
                + e.getMessage());
    }
}
    
