    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {

    if (idTransaksi == null || idTransaksi.equals("")) {

        JOptionPane.showMessageDialog(
                null,
                "Pilih transaksi terlebih dahulu");

        return;
    }

    if (jTextField2.getText().equals("")
            || jTextField3.getText().equals("")) {

        JOptionPane.showMessageDialog(
                null,
                "Hitung tarif terlebih dahulu");

        return;
    }

    Connection conn = koneksi.getConnection();

    String sql =
            "UPDATE transaksi SET "
            + "waktu_keluar=?, "
            + "total_tarif=?, "
            + "status='Selesai' "
            + "WHERE id_transaksi=?";

    PreparedStatement pst = conn.prepareStatement(sql);

    pst.setString(1, jTextField2.getText());
    pst.setString(2, jTextField3.getText());
    pst.setString(3, idTransaksi);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(
            null,
            "Kendaraan keluar berhasil disimpan");

    resetForm();
    loadTransaksiParkir();

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            null,
            "Data gagal disimpan : "
            + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
try {

    if (jComboBox1.getSelectedItem() == null) {
        return;
    }

    String data = jComboBox1.getSelectedItem().toString();

    idTransaksi = data.split(" - ")[0];

    Connection conn = koneksi.getConnection();

    String sql =
            "SELECT transaksi.waktu_masuk, transaksi.id_tarif, "
            + "tarif.tarif_minimum, tarif.tarif_perjam "
            + "FROM transaksi "
            + "JOIN tarif ON transaksi.id_tarif = tarif.id_tarif "
            + "WHERE transaksi.id_transaksi=?";

    PreparedStatement pst = conn.prepareStatement(sql);

    pst.setString(1, idTransaksi);

    ResultSet rs = pst.executeQuery();

    if (rs.next()) {

        jTextField1.setText(rs.getString("waktu_masuk"));

        idTarif = rs.getString("id_tarif");
        tarifMinimum = rs.getInt("tarif_minimum");
        tarifPerjam = rs.getInt("tarif_perjam");

        jTextField2.setText("");
        jTextField3.setText("");
    }

} catch (Exception e) {

    JOptionPane.showMessageDialog(
            null,
            "Gagal menampilkan detail transaksi : "
            + e.getMessage());
}        // TODO add your handling code here:
    }//GEN-LAST:event_jComboBox1ActionPerformed

